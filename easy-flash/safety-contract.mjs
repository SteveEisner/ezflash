// Chip family gate shared by the runtime and the hosted-catalog resolver.
// Longest family first so ESP32-C61 never falls into the ESP32-C6 bucket; only
// classic ESP32 die names collapse to plain ESP32 (unknown families fail closed).
export function chipFamily(value) {
	const chip=String(value).toUpperCase().replaceAll("_","-").replace(/\s+/g,"");
	for (const family of ["ESP32-C61","ESP32-S3","ESP32-S2","ESP32-C2","ESP32-C3","ESP32-C5","ESP32-C6","ESP32-H2","ESP32-P4","ESP8266"]) if (chip.startsWith(family)) return family;
	if (chip === "ESP32" || /^ESP32-(D|U|S0|PICO)/.test(chip)) return "ESP32";
	return chip;
}

// Temporary source-branch adapter for the merged-image safety gates. Replace this
// module with the canonical update-contract adapter when that dependency lands.
// Source: https://docs.espressif.com/projects/esptool/en/latest/esp32/esptool/basic-commands.html#write-binary-data-write-flash
// AI: below section was generated by an AI
const SHA256 = /^[0-9a-f]{64}$/;
const REQUIRED = new Set(["bootloader", "partitions", "boot-app0", "application"]);

function positiveInteger(value, label) {
	if (!Number.isSafeInteger(value) || value <= 0) throw new Error(`${label} must be a positive safe integer`);
}
// Component OFFSETS may legitimately be 0 (e.g. an ESP32-S3 bootloader image starts at 0x0);
// only byte SIZES must be strictly positive. Non-overlap is enforced separately below.
function nonNegativeInteger(value, label) {
	if (!Number.isSafeInteger(value) || value < 0) throw new Error(`${label} must be a non-negative safe integer`);
}

export function validateMergedImageStructure(target, artifact) {
	positiveInteger(target?.flashSizeBytes, "Target flash size");
	if (artifact?.transport !== "usb" || artifact.kind !== "complete-merged-image" || artifact.offset !== 0) throw new Error("USB merged-image transport contract mismatch");
	positiveInteger(artifact.sizeBytes, "Artifact size");
	if (!SHA256.test(artifact.sha256 || "")) throw new Error("Artifact SHA-256 is invalid");
	if (artifact.sizeBytes > target.flashSizeBytes) throw new Error("Artifact exceeds target flash size");
	if (!Array.isArray(artifact.components) || artifact.components.length !== REQUIRED.size) throw new Error("Required merged-image components are missing or duplicated");
	const ids = new Set(); const ranges = [];
	for (const component of artifact.components) {
		if (!REQUIRED.has(component.name) || ids.has(component.name)) throw new Error("Component ID is unknown or duplicated");
		ids.add(component.name); nonNegativeInteger(component.offset, `Component ${component.name} offset`); positiveInteger(component.sizeBytes, `Component ${component.name} size`);
		if (!SHA256.test(component.sha256 || "")) throw new Error(`Component ${component.name} SHA-256 is invalid`);
		const end = component.offset + component.sizeBytes;
		if (!Number.isSafeInteger(end) || end > artifact.sizeBytes) throw new Error(`Component ${component.name} exceeds merged image bounds`);
		if (end > target.flashSizeBytes) throw new Error(`Component ${component.name} exceeds target flash size`);
		ranges.push({ name:component.name,start:component.offset,end });
	}
	if ([...REQUIRED].some((name) => !ids.has(name))) throw new Error("Required merged-image components are missing");
	ranges.sort((left,right) => left.start-right.start);
	for (let index=1; index<ranges.length; index++) if (ranges[index].start < ranges[index-1].end) throw new Error(`Components ${ranges[index-1].name} and ${ranges[index].name} overlap`);
	return artifact.components.map((component) => ({ ...component,imageStart:component.offset }));
}

export async function validateMergedImageBytes(target, artifact, bytes, sha256Hex) {
	const components=validateMergedImageStructure(target,artifact);
	if (!(bytes instanceof Uint8Array) || bytes.byteLength !== artifact.sizeBytes) throw new Error("Merged image length mismatch");
	if (await sha256Hex(bytes) !== artifact.sha256) throw new Error("Artifact integrity verification failed");
	for (const component of components) {
		const slice=bytes.slice(component.imageStart,component.imageStart+component.sizeBytes);
		if (await sha256Hex(slice) !== component.sha256) throw new Error(`Component ${component.name} hash mismatch`);
	}
	return components;
}
